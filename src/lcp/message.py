"""Application-level message objects: :class:`Request`, :class:`Reply`, :class:`Response`."""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any

from .codec import decode_body, get_codec
from .enums import MessageType, Serializer, Status, status_name
from .errors import DecodeError, ServerBusyError, StatusError
from .frame import Frame
from .metadata import Metadata

if TYPE_CHECKING:
    from .auth import Principal
    from .session import Session


def error_body(
    status: int,
    message: str,
    *,
    details: Any = None,
    retry_after: float | None = None,
) -> bytes:
    """JSON error payload used for every non-OK reply generated by this package.

    ``{"error": {"code": 9, "name": "BUSY", "message": "...", "retry_after_ms": 50}}``.
    The shape is an implementation convention; the spec leaves error payloads open.
    """
    error: dict[str, Any] = {
        "code": int(status),
        "name": status_name(int(status)),
        "message": message,
    }
    if retry_after is not None:
        error["retry_after_ms"] = max(0, round(retry_after * 1000))
    if details is not None:
        error["details"] = details
    try:
        return json.dumps({"error": error}, separators=(",", ":"), ensure_ascii=False).encode()
    except (TypeError, ValueError):
        error["details"] = repr(details)
        return json.dumps({"error": error}, separators=(",", ":"), ensure_ascii=False).encode()


@dataclass(slots=True, repr=False)
class Request:
    """An inbound ``REQ`` or ``EVT`` as seen by a handler."""

    frame: Frame
    session: Session
    principal: Principal | None = None

    @property
    def path(self) -> str:
        """The ``TARGET_PATH`` (empty string if the frame carried none)."""
        return self.frame.metadata.target_path or ""

    @property
    def metadata(self) -> Metadata:
        return self.frame.metadata

    @property
    def payload(self) -> bytes:
        """The undecoded payload bytes."""
        return self.frame.payload

    @property
    def serializer(self) -> int:
        return self.frame.serializer

    @property
    def correlation_id(self) -> int:
        return self.frame.correlation_id

    @property
    def is_event(self) -> bool:
        return self.frame.msg_type is MessageType.EVT

    def body(self, message_type: Any = None) -> Any:
        """Decode the payload according to its *Serializer* byte.

        Invalid payloads raise :class:`~lcp.errors.DecodeError`, which the session turns
        into a ``BAD_REQUEST`` reply.  ``message_type`` is the Protobuf message class.
        """
        return decode_body(self.frame.serializer, self.frame.payload, message_type)

    def json(self) -> Any:
        """Decode the payload as JSON; any other serializer is a ``BAD_REQUEST``."""
        if self.frame.serializer != Serializer.JSON:
            raise DecodeError("payload is not JSON (serializer != 0x00)")
        return get_codec(Serializer.JSON).decode(self.frame.payload)

    def __repr__(self) -> str:
        return f"Request({self.frame.msg_type.name} {self.path!r} cid={self.correlation_id})"


@dataclass(slots=True)
class Reply:
    """Explicit handler result.  Plain return values are converted automatically:
    ``None`` → empty OK, ``bytes`` → RAW, protobuf messages → PROTOBUF, anything else → JSON."""

    body: Any = None
    status: int = Status.OK
    serializer: int | None = None


@dataclass(frozen=True, slots=True, repr=False)
class Response:
    """A ``RES`` (or ``EVT_ACK``) received by a client."""

    frame: Frame

    @property
    def status(self) -> int:
        return self.frame.status

    @property
    def ok(self) -> bool:
        return self.frame.status == Status.OK

    @property
    def payload(self) -> bytes:
        return self.frame.payload

    @property
    def serializer(self) -> int:
        return self.frame.serializer

    @property
    def metadata(self) -> Metadata:
        return self.frame.metadata

    @property
    def correlation_id(self) -> int:
        return self.frame.correlation_id

    def body(self, message_type: Any = None) -> Any:
        """Decode the payload according to its *Serializer* byte."""
        return decode_body(self.frame.serializer, self.frame.payload, message_type)

    def json(self) -> Any:
        if self.frame.serializer != Serializer.JSON:
            raise DecodeError("payload is not JSON (serializer != 0x00)")
        return get_codec(Serializer.JSON).decode(self.frame.payload)

    @property
    def error(self) -> dict[str, Any] | None:
        """The parsed ``{"error": {...}}`` object of a non-OK reply, if present."""
        if self.ok or self.frame.serializer != Serializer.JSON or not self.frame.payload:
            return None
        try:
            data = json.loads(self.frame.payload)
        except ValueError:
            return None
        error = data.get("error") if isinstance(data, dict) else None
        return error if isinstance(error, dict) else None

    @property
    def retry_after(self) -> float | None:
        """Seconds the server asked us to wait (``retry_after_ms``), if any."""
        error = self.error
        value = error.get("retry_after_ms") if error else None
        if isinstance(value, int | float) and not isinstance(value, bool) and value >= 0:
            return float(value) / 1000.0
        return None

    def raise_for_status(self) -> Response:
        """Return ``self`` if OK, else raise :class:`StatusError` / :class:`ServerBusyError`."""
        if self.ok:
            return self
        error = self.error or {}
        message = str(error.get("message") or status_name(self.status))
        if self.status == Status.BUSY:
            raise ServerBusyError(message, retry_after=self.retry_after)
        raise StatusError(self.status, message, details=error.get("details"))

    def __repr__(self) -> str:
        return (
            f"Response(status={status_name(self.status)} cid={self.correlation_id} "
            f"payload={len(self.payload)}B)"
        )
